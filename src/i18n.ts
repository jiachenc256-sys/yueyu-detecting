export function tf(key: string, vars: Record<string, string | number> = {}): string {
  let out = t(key);
  for (const [k, v] of Object.entries(vars)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

const TABLES: Record<SiteLocale, Dict> = {
  "zh-Hans": zhHans,
  "zh-Hant": zhHant,
  en,
};

let current: SiteLocale = "zh-Hans";
const listeners = new Set<(locale: SiteLocale) => void>();

export function getLocale(): SiteLocale {
  return current;
}

export function t(key: string): string {
  return TABLES[current][key] ?? TABLES.en[key] ?? key;
}

export function onLocaleChange(fn: (locale: SiteLocale) => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function isSiteLocale(value: string | null | undefined): value is SiteLocale {
  return value === "zh-Hans" || value === "zh-Hant" || value === "en";
}

export function detectInitialLocale(): SiteLocale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (isSiteLocale(saved)) return saved;
  } catch {
    /* ignore */
  }
  const nav = navigator.language.toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk") || nav.includes("hant")) return "zh-Hant";
  if (nav.startsWith("zh")) return "zh-Hans";
  return "en";
}

export function applyLocale(locale: SiteLocale): void {
  current = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    /* ignore */
  }

  document.documentElement.lang = locale === "en" ? "en" : locale;
  document.title = t("meta.title");

  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (!key) return;
    const value = t(key);
    if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, value);
      return;
    }
    if (el.dataset.i18nHtml === "true") {
      el.innerHTML = value;
      return;
    }
    el.textContent = value;
  });

  document.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (!key || !(el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement)) return;
    el.placeholder = t(key);
  });

  document.querySelectorAll<HTMLElement>("[data-visible-lang]").forEach((el) => {
    const allowed = (el.dataset.visibleLang ?? "")
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean);
    const show = allowed.includes(locale);
    el.hidden = !show;
    el.setAttribute("aria-hidden", show ? "false" : "true");
  });

  document.querySelectorAll<HTMLElement>("[data-locale-option]").forEach((el) => {
    const active = el.dataset.localeOption === locale;
    el.setAttribute("aria-pressed", active ? "true" : "false");
  });

  listeners.forEach((fn) => fn(locale));
}

export function setLocale(locale: SiteLocale): void {
  applyLocale(locale);
}

export function initI18n(): void {
  applyLocale(detectInitialLocale());

  document.querySelectorAll<HTMLElement>("[data-locale-option]").forEach((btn) => {
    btn.addEventListener("click", () => {
      const locale = btn.dataset.localeOption;
      if (isSiteLocale(locale)) setLocale(locale);
    });
  });
}
